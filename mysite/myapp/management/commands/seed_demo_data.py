class Command(BaseCommand):
    help = "Дополнить профили и резюме вымышленными данными до 20 записей в каждой таблице."

    @transaction.atomic
    def handle(self, *args, **options):
        profiles_needed = max(0, 20 - UserProfiles.objects.count())
        resumes_needed = max(0, 20 - Resume.objects.count())
        profiles_added = resumes_added = 0

        for index, person in enumerate(DEMO_PEOPLE, start=1):
            username, surname, name, age, city, profession, skills, about_me = person
            if profiles_added < profiles_needed and not UserProfiles.objects.filter(username=username).exists():
                profile = UserProfiles(
                    username=username, display_name=f"{name} {surname}", age=str(age),
                    city=city, ip_address=f"192.0.2.{index}", about_me=about_me,
                    email=f"{username.lower()}@example.com",
                )
                profile.full_clean()
                profile.save()
                profiles_added += 1

            if resumes_added < resumes_needed and not Resume.objects.filter(
                surname=surname, name=name, age=age, profession=profession,
            ).exists():
                resume = Resume(surname=surname, name=name, age=age,
                                profession=profession, skills=skills)
                resume.full_clean()
                resume.save()
                resumes_added += 1

        self.stdout.write(self.style.SUCCESS(
            f"Добавлено профилей: {profiles_added}; резюме: {resumes_added}. "
            f"Всего профилей: {UserProfiles.objects.count()}; резюме: {Resume.objects.count()}."
        ))
